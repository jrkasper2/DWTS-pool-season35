create table if not exists score_import_runs (
  id bigint generated by default as identity primary key,
  episode_slug text references episodes(slug) on delete cascade,
  ran_at timestamptz not null default now(),
  status text not null,
  source_url text,
  verification_url text,
  details jsonb not null default '{}'::jsonb
);
alter table score_import_runs enable row level security;

create or replace function score_episode(p_episode_slug text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  result_count int;
  prediction_count int;
begin
  select count(*) into result_count from results where episode_slug=p_episode_slug;
  if result_count=0 then raise exception 'No results loaded for episode'; end if;

  update predictions p
  set points =
    case abs(p.predicted_total-r.total)
      when 0 then 5
      when 1 then 3
      when 2 then 1
      else 0
    end
    + coalesce((
      select count(*)::int
      from generate_subscripts(p.judge_scores,1) s(i)
      where s.i <= coalesce(array_length(r.judge_scores,1),0)
        and p.judge_scores[s.i]=r.judge_scores[s.i]
    ),0)
  from results r
  where p.episode_slug=p_episode_slug
    and r.episode_slug=p_episode_slug
    and r.couple_slug=p.couple_slug;

  update bonus_picks b
  set points =
    case when exists (
      select 1 from results r
      where r.episode_slug=p_episode_slug
        and r.couple_slug=b.highest_slug
        and r.highest
    ) then 5 else 0 end
    +
    case when exists (
      select 1 from results r
      where r.episode_slug=p_episode_slug
        and r.couple_slug=b.eliminated_slug
        and r.eliminated
    ) then 5 else 0 end
  where b.episode_slug=p_episode_slug;

  update couples c
  set active=false
  where exists (
    select 1 from results r
    where r.episode_slug=p_episode_slug
      and r.couple_slug=c.slug
      and r.eliminated
  );

  update episodes
  set status='scored', scored_at=now()
  where slug=p_episode_slug;

  select count(*) into prediction_count from predictions where episode_slug=p_episode_slug;

  return jsonb_build_object(
    'episode_slug',p_episode_slug,
    'results',result_count,
    'predictions_scored',prediction_count
  );
end $$;

revoke all on function score_episode(text) from public, anon, authenticated;
grant execute on function score_episode(text) to service_role;

