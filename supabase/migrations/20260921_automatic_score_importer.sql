-- In the hosted project, project URL and publishable key are stored in Vault
-- as dwts_project_url and dwts_publishable_key. The cron job retries on
-- Tuesdays and Wednesdays until an ended episode is successfully scored.
select cron.schedule(
  'dwts-score-importer',
  '5,35 * * * 2,3',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets where name='dwts_project_url')
      || '/functions/v1/dwts-score-importer',
    headers := jsonb_build_object(
      'Content-Type','application/json',
      'apikey',(select decrypted_secret from vault.decrypted_secrets where name='dwts_publishable_key'),
      'Authorization','Bearer ' || (select decrypted_secret from vault.decrypted_secrets where name='dwts_publishable_key')
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 20000
  );
  $$
);